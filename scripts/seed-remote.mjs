async function callApi(action, body) {
  const res = await fetch(`${BASE}/admin/api/${action}?key=${KEY}`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const txt = await res.text();
    throw new Error(`API ${action} failed: ${res.status} ${txt}`);
  }
  return res.json();
}

